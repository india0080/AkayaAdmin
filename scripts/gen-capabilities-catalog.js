// Regenerates src/features/capabilities/catalogData.ts from the app's
// akaya_ai/assets/capabilities/catalog.json (the source of truth).
//
//   node scripts/gen-capabilities-catalog.js
//
// The console cannot read the app's assets at runtime, so it bundles a typed
// copy of id / category / baseStatus / labels / descriptions. A parity test
// (src/__tests__/capabilities.test.ts) fails when the copy drifts.
const fs = require("node:fs");
const path = require("node:path");

const SRC = path.resolve(__dirname, "../../akaya_ai/assets/capabilities/catalog.json");
const OUT = path.resolve(__dirname, "../src/features/capabilities/catalogData.ts");

const json = JSON.parse(fs.readFileSync(SRC, "utf8"));
const entries = json.entries.map((e) => ({
  id: e.id,
  category: e.category,
  baseStatus: e.baseStatus,
  labels: { en: e.labels.en, hi: e.labels.hi, hinglish: e.labels.hinglish },
  descriptions: { en: e.descriptions.en, hi: e.descriptions.hi, hinglish: e.descriptions.hinglish },
}));

const out = `// GENERATED by scripts/gen-capabilities-catalog.js from
// akaya_ai/assets/capabilities/catalog.json. Do not edit by hand.
import type { CatalogEntry } from "./catalog";

export const CATALOG_VERSION = ${JSON.stringify(json.version)};

export const CATALOG_DATA: readonly CatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${entries.length} entries to ${path.relative(process.cwd(), OUT)}`);
